const MONTH_KEYS = [
  "january",
  "february",
  "march",
  "april",
  "may",
  "june",
  "july",
  "august",
  "september",
  "october",
  "november",
  "december",
];

function season(peakMonths, goodMonths, shoulderMonths = []) {
  const values = Object.fromEntries(MONTH_KEYS.map((month) => [month, 10]));
  shoulderMonths.forEach((month, index) => {
    values[month] = 50 - index * 5;
  });
  goodMonths.forEach((month, index) => {
    values[month] = 80 - index * 5;
  });
  peakMonths.forEach((month, index) => {
    values[month] = 100 - index * 5;
  });
  return values;
}

